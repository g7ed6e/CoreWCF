        /// <summary>
        /// Emits the <c>i:type</c> attribute naming a contract.
        /// </summary>
        /// <remarks>
        /// Mirrors XmlWriterDelegator.WriteAttributeQualifiedName: the value's namespace is declared
        /// first, then the attribute is opened and the qualified name written into it. Declaring
        /// first is what lets the writer reuse a prefix already in scope - which is why i:type on a
        /// contract in the root's own namespace reads "a:Derived" and adds no declaration, while one
        /// in a different namespace brings its own xmlns with it.
        /// </remarks>
        private void EmitXsiType(Indentor indentor, ContractSpec contract) =>
            EmitXsiType(indentor, contract.ContractName, contract.ContractNamespace);

        private void EmitXsiType(Indentor indentor, string name, string ns)
        {
            _builder.AppendLine($"{indentor}writer.WriteXmlnsAttribute(null, {Literal(ns)});");
            _builder.AppendLine($"{indentor}writer.WriteStartAttribute(\"i\", \"type\", {Literal(SchemaInstanceNamespace)});");
            _builder.AppendLine($"{indentor}writer.WriteQualifiedName({Literal(name)}, {Literal(ns)});");
            _builder.AppendLine($"{indentor}writer.WriteEndAttribute();");
        }

        /// <summary>
        /// The statement that writes a member's value.
        /// </summary>
        /// <remarks>
        /// Every case here matches XmlWriterDelegator in dotnet/runtime. The non-obvious ones:
        /// char is written as its numeric value, not as a character; Guid, TimeSpan and ulong go
        /// through WriteRaw because XmlWriter has no WriteValue overload for them; byte[] is base64.
        /// ulong is the one that bites quietly - WriteValue(ulong) is not missing so much as
        /// ambiguous, since ulong converts implicitly to float, double and decimal and to none of
        /// them better than the others, so the mistake surfaces as CS0121 in generated code rather
        /// than as wrong output.
        /// </remarks>
        private static string WriteValueStatement(MemberKind kind, string value) => kind switch
        {
            MemberKind.Char => $"writer.WriteValue((int){value});",
            MemberKind.Guid => $"writer.WriteRaw({value}.ToString());",
            MemberKind.TimeSpan => $"writer.WriteRaw({XmlConvert}.ToString({value}));",
            MemberKind.UInt64 => $"writer.WriteRaw({XmlConvert}.ToString({value}));",
            MemberKind.ByteArray => $"writer.WriteBase64({value}, 0, {value}.Length);",

            // Not ToString(): SerializationInfoString is the round-trippable form, and it is what
            // adds the trailing slash the fixtures record for an authority-only Uri.
            MemberKind.Uri =>
                $"writer.WriteString({value}.GetComponents(global::System.UriComponents.SerializationInfoString, global::System.UriFormat.UriEscaped));",

            MemberKind.DateTimeOffset => $"WriteDateTimeOffset(writer, {value});",
            MemberKind.QName => $"WriteQName(writer, {value});",
            _ => $"writer.WriteValue({value});"
        };

        /// <summary>
        /// The test for "this member is at its type's default", as
        /// <c>EmitDefaultValue = false</c> defines it.
        /// </summary>
        private static string IsDefaultExpression(MemberSpec member, string access)
        {
            if (member.IsNullableValueType)
            {
                return $"!{access}.HasValue";
            }

            return member.Kind switch
            {
                MemberKind.String or MemberKind.ByteArray or MemberKind.Contract or MemberKind.Collection or MemberKind.Dictionary
                    or MemberKind.Object or MemberKind.Uri or MemberKind.QName => $"{access} == null",
                MemberKind.Boolean => $"!{access}",
                _ => $"{access} == default"
            };
        }

        /// <summary>
        /// Emits the shared enum writer: one copy of the algorithm, driven by a per-enum table.
        /// </summary>
        /// <remarks>
        /// Mirrors EnumDataContract.WriteEnumValue. An exact value match wins even for a flags enum,
        /// which is why the combined value is looked up before any decomposition. A flags value that
        /// cannot be fully decomposed is an error rather than a partial write, and a zero that
        /// matched nothing falls back to the member declared as zero, if there is one.
        /// </remarks>
        private void EmitEnumHelper(Indentor indentor)
        {
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static void WriteEnum({DictionaryWriter} writer, long longValue, long[] values, string[] names, bool isFlags, string typeName)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}for (int i = 0; i < values.Length; i++)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}if (longValue == values[i])");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}writer.WriteString(names[i]);");
            _builder.AppendLine($"{indentor}return;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}if (isFlags)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}int zeroIndex = -1;");
            _builder.AppendLine($"{indentor}bool noneWritten = true;");
            _builder.AppendLine($"{indentor}for (int i = 0; i < values.Length; i++)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}long current = values[i];");
            _builder.AppendLine($"{indentor}if (current == 0) {{ zeroIndex = i; continue; }}");
            _builder.AppendLine($"{indentor}if (longValue == 0) {{ break; }}");
            _builder.AppendLine($"{indentor}if ((current & longValue) == current)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}if (noneWritten) {{ noneWritten = false; }} else {{ writer.WriteString(\" \"); }}");
            _builder.AppendLine($"{indentor}writer.WriteString(names[i]);");
            _builder.AppendLine($"{indentor}longValue &= ~current;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}if (longValue != 0)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}throw new global::System.Runtime.Serialization.SerializationException(\"Invalid enum value on write for \" + typeName + \".\");");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}if (noneWritten && zeroIndex >= 0)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}writer.WriteString(names[zeroIndex]);");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}return;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}throw new global::System.Runtime.Serialization.SerializationException(\"Invalid enum value on write for \" + typeName + \".\");");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// Emits the per-call object-identity table behind <c>IsReference</c>.
        /// </summary>
        /// <remarks>
        /// Mirrors ObjectToIdCache and XmlObjectSerializerWriteContext.OnHandleIsReference in
        /// dotnet/runtime. Two details are load-bearing and neither is obvious: ids start at 1, and
        /// lookup is by reference, never by Equals - a contract that overrides equality must still
        /// get one id per instance, and two equal-but-distinct instances must not collapse into a
        /// z:Ref. The z prefix is never declared explicitly; writing an attribute in the
        /// serialization namespace makes the writer declare it wherever it first comes into scope,
        /// which is what puts xmlns:z on the root for a reference root and on the member element
        /// when only a nested contract is one.
        /// </remarks>
        private void EmitReferenceScope(Indentor indentor)
        {
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private sealed class {ReferenceScope}");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}private global::System.Collections.Generic.Dictionary<object, int> _ids;");
            _builder.AppendLine($"{indentor}private global::System.Collections.Generic.HashSet<object> _byValueInScope;");
            _builder.AppendLine($"{indentor}private int _next = 1;");
            _builder.AppendLine($"{indentor}private int _depth;");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}/// <summary>Depth past which a by-value graph starts being checked for cycles.</summary>");
            _builder.AppendLine($"{indentor}private const int DepthToCheckCyclicReference = 512;");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}/// <summary>Enters a contract written by value, throwing if it is already on the path.</summary>");
            _builder.AppendLine($"{indentor}internal void EnterByValue(object value)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}if (++_depth < DepthToCheckCyclicReference)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}return;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}if (_byValueInScope == null)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}_byValueInScope = new global::System.Collections.Generic.HashSet<object>(");
            indentor.Increment();
            _builder.AppendLine($"{indentor}global::System.Collections.Generic.ReferenceEqualityComparer.Instance);");
            indentor.Decrement();
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}if (!_byValueInScope.Add(value))");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}throw new global::System.Runtime.Serialization.SerializationException(");
            indentor.Increment();
            _builder.AppendLine($"{indentor}\"Object graph for type '\" + value.GetType().FullName + \"' contains cycles and cannot be \" +");
            _builder.AppendLine($"{indentor}\"serialized if references are not tracked. Consider using the DataContractAttribute \" +");
            _builder.AppendLine($"{indentor}\"with the IsReference property set to true.\");");
            indentor.Decrement();
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}internal void ExitByValue(object value)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}if (_depth >= DepthToCheckCyclicReference && _byValueInScope != null)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}_byValueInScope.Remove(value);");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}_depth--;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}/// <summary>Returns true when z:Ref was written, meaning the content must not be repeated.</summary>");
            _builder.AppendLine($"{indentor}internal bool WriteIdOrRef({DictionaryWriter} writer, object value)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}if (_ids == null)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}_ids = new global::System.Collections.Generic.Dictionary<object, int>(");
            indentor.Increment();
            _builder.AppendLine($"{indentor}global::System.Collections.Generic.ReferenceEqualityComparer.Instance);");
            indentor.Decrement();
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}int id;");
            _builder.AppendLine($"{indentor}if (_ids.TryGetValue(value, out id))");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}writer.WriteAttributeString(\"z\", \"Ref\", {Literal(SerializationNamespace)}, Id(id));");
            _builder.AppendLine($"{indentor}return true;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}id = _next++;");
            _builder.AppendLine($"{indentor}_ids.Add(value, id);");
            _builder.AppendLine($"{indentor}writer.WriteAttributeString(\"z\", \"Id\", {Literal(SerializationNamespace)}, Id(id));");
            _builder.AppendLine($"{indentor}return false;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static string Id(int id) =>");
            indentor.Increment();
            _builder.AppendLine($"{indentor}\"i\" + id.ToString(global::System.Globalization.CultureInfo.InvariantCulture);");
            indentor.Decrement();
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        private void EmitEnumTable(Indentor indentor, EnumSpec enumSpec)
        {
            int index = _enumIndexes[enumSpec.FullyQualifiedName];

            List<string> values = new();
            List<string> names = new();
            foreach (EnumMemberSpec member in enumSpec.Members)
            {
                values.Add(member.Value.ToString(System.Globalization.CultureInfo.InvariantCulture) + "L");
                names.Add(Literal(member.Name));
            }

            _builder.AppendLine($"{indentor}// {enumSpec.FullyQualifiedName}");
            _builder.AppendLine($"{indentor}private static readonly long[] __EnumValues{index} = new long[] {{ {string.Join(", ", values)} }};");
            _builder.AppendLine($"{indentor}private static readonly string[] __EnumNames{index} = new string[] {{ {string.Join(", ", names)} }};");
        }

        /// <summary>
        /// Emits the writer for <c>DateTimeOffset</c>, which is a contract rather than a primitive.
        /// </summary>
        /// <remarks>
        /// Mirrors DateTimeOffsetAdapter in dotnet/runtime, the struct contract
        /// DataContractSerializer swaps in: two members named DateTime and OffsetMinutes, in the
        /// System namespace, sorted the same way every contract's members are - which puts DateTime
        /// first by ordinal name. The value written is <c>UtcDateTime</c>, not the local one, so the
        /// element carries a Z and the offset is recorded separately rather than twice.
        /// </remarks>
        private void EmitDateTimeOffsetHelper(Indentor indentor)
        {
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static void WriteDateTimeOffset({DictionaryWriter} writer, global::System.DateTimeOffset value)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}writer.WriteStartElement(\"DateTime\", {Literal(SystemContractNamespace)});");
            _builder.AppendLine($"{indentor}writer.WriteValue(value.UtcDateTime);");
            _builder.AppendLine($"{indentor}writer.WriteEndElement();");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}writer.WriteStartElement(\"OffsetMinutes\", {Literal(SystemContractNamespace)});");
            _builder.AppendLine($"{indentor}writer.WriteValue((short)value.Offset.TotalMinutes);");
            _builder.AppendLine($"{indentor}writer.WriteEndElement();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// Emits the writer for an <c>XmlQualifiedName</c> value.
        /// </summary>
        /// <remarks>
        /// Mirrors XmlWriterDelegator.WriteQName. The empty name writes nothing at all - not an
        /// empty string - and otherwise the value's namespace is declared before the qualified name
        /// is written, so the writer has a prefix to render it with.
        /// </remarks>
        private void EmitQNameHelper(Indentor indentor)
        {
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static void WriteQName({DictionaryWriter} writer, global::System.Xml.XmlQualifiedName value)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}if (value != global::System.Xml.XmlQualifiedName.Empty)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}writer.WriteXmlnsAttribute(null, value.Namespace);");
            _builder.AppendLine($"{indentor}writer.WriteQualifiedName(value.Name, value.Namespace);");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// Emits the writer for one item of an <c>object[]</c>, whose element is already open.
        /// </summary>
        /// <remarks>
        /// Deliberately narrower than a member's boxed switch: it covers the primitives, a bare
        /// object and null, and throws for anything else. A contract or enum inside an untyped array
        /// would need the containing contract's known types, which an item writer shared across the
        /// whole context does not have.
        /// </remarks>
        private void EmitAnyTypeHelper(Indentor indentor)
        {
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static void WriteAnyType({DictionaryWriter} writer, object value)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}if (value == null)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}WriteNil(writer);");
            _builder.AppendLine($"{indentor}return;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}global::System.Type __runtimeType = value.GetType();");
            _builder.AppendLine($"{indentor}if (__runtimeType == typeof(object))");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}// anyType: neither i:type nor content");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");

            foreach ((string clrType, MemberKind kind, string xsiName, string xsiNamespace, bool _) in BoxedPrimitives)
            {
                _builder.AppendLine($"{indentor}else if (__runtimeType == typeof({clrType}))");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                EmitXsiType(indentor, xsiName, xsiNamespace);
                _builder.AppendLine($"{indentor}{WriteValueStatement(kind, $"(({clrType})value)")}");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }

            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}throw new global::System.Runtime.Serialization.SerializationException(");
            indentor.Increment();
            _builder.AppendLine($"{indentor}\"Type '\" + __runtimeType.FullName + \"' cannot be written as an untyped array item.\");");
            indentor.Decrement();
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        private void EmitNilHelper(Indentor indentor)
        {
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static void WriteNil({DictionaryWriter} writer)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}writer.WriteAttributeString(\"i\", \"nil\", {Literal(SchemaInstanceNamespace)}, \"true\");");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        private string SerializerTypeName(ContractSpec contract) =>
            "__DataContractSerializer" + _contractIndexes[contract.FullyQualifiedName].ToString();

        private string ContentWriterName(ContractSpec contract) => ContentWriterName(contract.FullyQualifiedName);

        private string ContentWriterName(string fullyQualifiedName) =>
            "__WriteContent" + _contractIndexes[fullyQualifiedName].ToString();

        private static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
    }
